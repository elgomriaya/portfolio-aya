/* =========================================
   2. CHANGEMENT DE LANGUE
========================================= */

function setLanguage(language) {
    const selectedLanguage = translations[language]
        ? language
        : "fr";

    const dictionary = translations[selectedLanguage];

    document.documentElement.lang = selectedLanguage;

    // Mettre à jour le titre de la page
    if (dictionary.pageTitle) {
        document.title = dictionary.pageTitle;
    }

    // Mettre à jour la description SEO
    const description = document.querySelector(
        'meta[name="description"]'
    );

    if (description && dictionary.metaDescription) {
        description.setAttribute(
            "content",
            dictionary.metaDescription
        );
    }

    // Traduire les éléments textuels
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.textContent = dictionary[key];
        }
    });

    // Traduire les attributs alt des images
    document.querySelectorAll("[data-i18n-alt]").forEach(element => {
        const key = element.getAttribute("data-i18n-alt");

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.setAttribute("alt", dictionary[key]);
        }
    });

    // Traduire les placeholders si le HTML en contient
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.getAttribute("data-i18n-placeholder");

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.setAttribute("placeholder", dictionary[key]);
        }
    });

    // Actualiser l'état du sélecteur de langue
    document.querySelectorAll(".lang-btn").forEach(button => {
        const isActive =
            button.dataset.lang === selectedLanguage;

        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    // Mémoriser la langue dans cette page
    try {
        localStorage.setItem("portfolio-language", selectedLanguage);
    } catch (error) {
        // Le site reste utilisable si le stockage est indisponible.
    }
}


/* =========================================
   3. INITIALISATION DU SÉLECTEUR DE LANGUE
========================================= */

document.querySelectorAll(".lang-btn").forEach(button => {
    button.addEventListener("click", () => {
        const language = button.dataset.lang;

        if (language) {
            setLanguage(language);
        }
    });
});


/* =========================================
   4. MENU MOBILE
========================================= */

function initializeMobileMenu() {
    const menuButton = document.querySelector(
        ".menu-toggle, .nav-toggle, .hamburger"
    );

    const navigation = document.querySelector(".nav");

    if (!menuButton || !navigation) {
        return;
    }

    menuButton.addEventListener("click", () => {
        const isOpen = navigation.classList.toggle("open");

        menuButton.classList.toggle("active", isOpen);
        menuButton.setAttribute("aria-expanded", String(isOpen));
    });

    // Fermer le menu après le clic sur un lien
    navigation.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", () => {
            navigation.classList.remove("open");
            menuButton.classList.remove("active");
            menuButton.setAttribute("aria-expanded", "false");
        });
    });

    // Fermer le menu si l'écran repasse en grand format
    window.addEventListener("resize", () => {
        if (window.innerWidth > 760) {
            navigation.classList.remove("open");
            menuButton.classList.remove("active");
            menuButton.setAttribute("aria-expanded", "false");
        }
    });
}


/* =========================================
   5. ANIMATIONS AU DÉFILEMENT
========================================= */

function initializeRevealAnimations() {
    const elements = document.querySelectorAll(".reveal");

    if (!("IntersectionObserver" in window)) {
        elements.forEach(element => {
            element.classList.add("visible");
        });

        return;
    }

    const observer = new IntersectionObserver(
        (entries, currentObserver) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add("visible");
                    currentObserver.unobserve(entry.target);
                }
            });
        },
        {
            threshold: 0.12,
            rootMargin: "0px 0px -30px 0px"
        }
    );

    elements.forEach(element => observer.observe(element));
}


/* =========================================
   6. LIEN ACTIF DANS LA NAVIGATION
========================================= */

function initializeActiveNavigation() {
    const sections = document.querySelectorAll("main section[id]");
    const navLinks = document.querySelectorAll(".nav a[href^='#']");

    if (!sections.length || !navLinks.length) {
        return;
    }

    if (!("IntersectionObserver" in window)) {
        return;
    }

    const observer = new IntersectionObserver(
        entries => {
            entries.forEach(entry => {
                if (!entry.isIntersecting) {
                    return;
                }

                const sectionId = entry.target.id;

                navLinks.forEach(link => {
                    const isActive =
                        link.getAttribute("href") === `#${sectionId}`;

                    link.classList.toggle("active", isActive);
                });
            });
        },
        {
            rootMargin: "-25% 0px -60% 0px",
            threshold: 0
        }
    );

    sections.forEach(section => observer.observe(section));
}


/* =========================================
   7. ANNÉE AUTOMATIQUE DU COPYRIGHT
========================================= */

function initializeCopyrightYear() {
    const yearElements = document.querySelectorAll(
        "#current-year, #year, [data-current-year]"
    );

    yearElements.forEach(element => {
        element.textContent = new Date().getFullYear();
    });
}


/* =========================================
   8. BOUTON RETOUR EN HAUT
========================================= */

function initializeBackToTop() {
    const buttons = document.querySelectorAll(
        ".back-to-top, #backToTop"
    );

    buttons.forEach(button => {
        button.addEventListener("click", event => {
            const href = button.getAttribute("href");

            if (href === "#" || !href) {
                event.preventDefault();

                window.scrollTo({
                    top: 0,
                    behavior: "smooth"
                });
            }
        });
    });
}


/* =========================================
   9. ANNÉE ET LIENS EXTERNES
========================================= */

function initializeExternalLinks() {
    document.querySelectorAll('a[target="_blank"]').forEach(link => {
        link.setAttribute("rel", "noopener noreferrer");
    });
}


/* =========================================
   10. LANCEMENT DU SCRIPT
========================================= */

document.addEventListener("DOMContentLoaded", () => {
    // Langue française par défaut, sauf préférence enregistrée
    let savedLanguage = "fr";

    try {
        const storedLanguage = localStorage.getItem(
            "portfolio-language"
        );

        if (storedLanguage && translations[storedLanguage]) {
            savedLanguage = storedLanguage;
        }
    } catch (error) {
        // La langue française reste la langue par défaut.
    }

    setLanguage(savedLanguage);

    initializeMobileMenu();
    initializeRevealAnimations();
    initializeActiveNavigation();
    initializeCopyrightYear();
    initializeBackToTop();
    initializeExternalLinks();
});
